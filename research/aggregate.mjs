// Turns research/results/*.json into a draft report. The public draft only
// contains aggregate numbers; the per-server table goes to a private file so
// nothing unpatched is published before the maintainers are told.
//   node research/aggregate.mjs
import { readdirSync, readFileSync, writeFileSync } from 'node:fs';

const dir = 'research/results';
const results = readdirSync(dir)
  .filter((f) => f.endsWith('.json'))
  .map((f) => JSON.parse(readFileSync(`${dir}/${f}`, 'utf8')));
const ok = results.filter((r) => !r.error);
const pct = (n, d) => (d ? `${Math.round((n / d) * 100)}%` : '—');
const has = (r, pred) => r.findings.some(pred);

const ATTACK_IDS = new Set(['tool-poisoning', 'invisible-characters', 'tool-output-injection', 'llm-tool-poisoning']);
const rows = [
  ['Hidden instructions in tool metadata (critical)', ok.filter((r) => has(r, (f) => ATTACK_IDS.has(f.id))).length],
  ['Code or command execution tool', ok.filter((r) => has(r, (f) => f.id === 'capability-exec')).length],
  ['Destructive tool (delete, drop…)', ok.filter((r) => has(r, (f) => f.id === 'capability-destructive')).length],
  ['Money-moving tool', ok.filter((r) => has(r, (f) => f.id === 'capability-financial')).length],
  ['Private data + outbound channel on one server', ok.filter((r) => has(r, (f) => f.id === 'exfiltration-path')).length],
  ['Tool claims read-only but changes state', ok.filter((r) => has(r, (f) => f.id === 'annotation-mismatch')).length],
  ['High-impact tool without destructiveHint', ok.filter((r) => has(r, (f) => f.id === 'missing-annotations')).length],
  ['Free-form path/url/command/query parameter', ok.filter((r) => has(r, (f) => f.id === 'unconstrained-input')).length],
];
const tools = ok.reduce((n, r) => n + r.tools.length, 0);

const today = new Date().toISOString().slice(0, 10);
const md = [
  `# State of MCP Security: draft (${today})`,
  '',
  `**${results.length}** public MCP servers in the target list; **${ok.length}** started and listed their tools (**${tools}** tools in total). The rest needed credentials or failed to start in the sandbox.`,
  '',
  'Each server ran in an isolated container. Probe only listed tool definitions (no tool was called) and applied its static rules.',
  '',
  '| Finding | Servers | Share |',
  '|---|---|---|',
  ...rows.map(([label, n]) => `| ${label} | ${n} | ${pct(n, ok.length)} |`),
  '',
  '> Capability findings ("can execute commands") describe *what an agent could be tricked into doing*. They are not vulnerabilities by themselves. Only the first row is evidence of an attack.',
  '',
  '_Draft generated by `research/aggregate.mjs`. Do not publish server names with unresolved critical findings until the disclosure period ends (see research/README.md)._',
].join('\n');
writeFileSync('research/REPORT-draft.md', `${md}\n`);

const privateRows = ok
  .map((r) => {
    const sev = (s) => r.findings.filter((f) => f.severity === s).length;
    const caps = new Set(r.findings.filter((f) => f.id.startsWith('capability-')).map((f) => f.id.slice(11)));
    return `| ${r.package} | ${r.tools.length} | ${sev('critical')} | ${sev('high')} | ${[...caps].join(', ')} |`;
  })
  .concat(results.filter((r) => r.error).map((r) => `| ${r.package} | did not start | | | |`));
writeFileSync(
  `${dir}/PRIVATE-by-server.md`,
  ['# Per-server results (private: do not publish before disclosure)', '', '| Package | Tools | Critical | High | Capabilities |', '|---|---|---|---|---|', ...privateRows].join('\n') + '\n',
);
console.log(md);
console.log(`\nPrivate per-server table: ${dir}/PRIVATE-by-server.md`);
